#!/usr/bin/env python3
"""Regenerate the prototype's generated assets from the viewer's synced artefacts.

    python3 -I tools/build-assets.py /path/to/dea-web-viewer

Writes (inside this folder):
    js/icons.js   — icon path data, lifted from the lucide-react version the viewer ships
    js/data.js    — the real metamodel: entity-graph.json entities/relationships
                    + attributes parsed from metamodel.puml (same regex as the app)

Everything is read-only against the viewer repo. Re-run after the viewer's
CI sync pulls a new metamodel so the prototype keeps showing real data.
"""
import json
import os
import re
import sys

VIEWER = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Developer/dea-web-viewer")
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)

# ── icons ────────────────────────────────────────────────────────────
ICONS = """
house workflow network grid-3x3 route bar-chart-3 book-open users search download link
ellipsis x plus minus maximize minimize rotate-ccw check external-link copy chevron-down
chevron-up chevron-right chevron-left chevrons-left chevrons-right arrow-right arrow-left
arrow-up arrow-down arrow-up-right corner-down-right arrow-left-right sliders-horizontal
layers keyboard info circle-help filter sparkles target zap git-branch file-json file-code
image share-2 undo-2 move hand scan list table hash database compass grip-horizontal
monitor smartphone tablet mouse-pointer-2 panel-left panel-right eye-off book-marked box
component shapes map-pin search-check file-text circle-dashed
""".split()

CAMEL = re.compile(r"(?<!^)(?=[A-Z])")


def read_icon(name):
    path = os.path.join(VIEWER, "node_modules/lucide-react/dist/esm/icons", name + ".js")
    with open(path, encoding="utf-8") as fh:
        src = fh.read()
    alias = re.search(r"export \{ default \} from '\./([\w-]+)\.js'", src)   # e.g. bar-chart-3 → chart-column
    if alias:
        return read_icon(alias.group(1))
    node = re.compile(r'\[\s*"(\w+)",\s*\{(.*?)\}\s*\]', re.S)   # nodes span several lines when long
    parts = []
    for tag, attrs in node.findall(src):
        out = []
        for key, val in re.findall(r'(\w+):\s*"([^"]*)"', attrs):
            if key == "key":
                continue
            out.append('%s="%s"' % (CAMEL.sub("-", key), val))
        parts.append("<%s %s/>" % (tag, " ".join(out)))
    expected = src.count('key: "')                       # every node carries a React key
    if len(parts) != expected or not parts:
        raise SystemExit("icon %s: extracted %d of %d nodes" % (name, len(parts), expected))
    return "".join(parts)


icons = {name: read_icon(name) for name in ICONS}
with open(os.path.join(OUT, "js/icons.js"), "w", encoding="utf-8") as fh:
    fh.write("/* Generated by tools/build-assets.py — do not edit by hand.\n")
    fh.write("   Icon path data from lucide-react (ISC license), the version dea-web-viewer ships. */\n")
    fh.write("window.DEA_ICONS = ")
    json.dump(icons, fh, ensure_ascii=False, indent=0, separators=(",", ":"))
    fh.write(";\n")

# ── model data ───────────────────────────────────────────────────────
with open(os.path.join(VIEWER, "public/data/entity-graph.json"), encoding="utf-8") as fh:
    graph = json.load(fh)
with open(os.path.join(VIEWER, "public/data/metamodel.puml"), encoding="utf-8") as fh:
    puml = fh.read()

# Attributes: `+ name : type` lines inside `entity "Name" as ALIAS { … }` blocks.
attrs, current = {}, None
for raw in puml.split("\n"):
    line = raw.strip()
    m = re.match(r'^entity\s+"([^"]+)"\s+as\s+([A-Za-z0-9_]+)(\s*\{)?$', line)
    if m:
        current = m.group(2)
        if not m.group(3):
            current = None
        continue
    if current and line.startswith("+"):
        a = re.match(r"^\+\s*([A-Za-z0-9_]+)\s*:\s*(.+)$", line)
        if a:
            attrs.setdefault(current, []).append([a.group(1), a.group(2)])
    elif current and line == "}":
        current = None

layers = [
    {
        "id": l["id"],
        "code": l["id"],
        "name": l["name"],
        "qualifier": l.get("qualifier", ""),
        "color": l.get("color"),
        "ink": l.get("dark_color"),
    }
    for l in graph["layers"]
]
dims = sorted({e.get("dimension", "") for e in graph["entities"] if not e.get("layer")})
dim_names = {d["id"]: d["name"] for d in graph.get("dimensions", [])}
dim_label = (
    dim_names.get(dims[0], "Dimension")
    if len(dims) == 1
    else "Cross-Cutting Dimensions"
)
layers.append({"id": "DIM", "code": "L6", "name": dim_label, "qualifier": "Cross-cutting",
               "color": "#9CA3AF", "ink": "#4B5563"})

entities = []
for e in graph["entities"]:
    membership = e.get("membership") or None
    cs = e.get("catalog_summary") or None
    entities.append({
        "a": e["class_alias"],
        "n": e["display_name"],
        "l": e.get("layer") or "DIM",
        "s": e.get("status"),
        "d": e.get("description", ""),
        "at": attrs.get(e["class_alias"], []),
        "m": [membership["kind"], membership.get("profile")] if membership else None,
        "repo": e.get("catalog_repo"),
        "url": e.get("repo_url"),
        "eid": e.get("entity_id"),
        "bb": e.get("building_block_name"),
        "sp": e.get("specializes"),
        "dim": e.get("dimension"),
        "abs": bool(e.get("abstract")),
        "ecf": e.get("ecf_coordinates") if "ecf_coordinates" in e else None,
        "cs": [cs["entity_count"], cs["canonical"], cs["candidates"], cs["retired"]]
        if cs and cs["entity_count"] > 0 else None,
    })

rels = [
    {"f": r["from"], "t": r["to"], "l": r["label"], "k": r["rel_type"],
     "c": r.get("cardinality", ""), "d": 1 if r.get("style") == "dashed" else 0,
     "i": (r.get("rel_ids") or [None])[0]}
    for r in graph["relationships"]
]
# Specialisation edges are derived from entity.specializes, exactly as the app does.
rels += [{"f": e["a"], "t": e["sp"], "l": "specializes", "k": "specialization",
          "c": "", "d": 0, "i": None}
         for e in entities if e["sp"]]

used = {r["i"] for r in rels if r["i"]}
defs = {
    d["id"]: {"name": d.get("name", ""), "def": d.get("definition", ""),
              "cat": d.get("category", ""), "life": d.get("lifecycle", "")}
    for d in graph.get("relationship_definitions", [])
    if d.get("id") in used
}

data = {
    "meta": {
        "version": graph.get("metamodel_version"),
        "modelRepo": graph.get("opendeam_model_repo"),
        "modelPin": graph.get("opendeam_model_pin"),
        "counts": {"entities": len(entities), "relationships": len(rels)},
    },
    "layers": layers,
    "entities": entities,
    "rels": rels,
    "defs": defs,
}
with open(os.path.join(OUT, "js/data.js"), "w", encoding="utf-8") as fh:
    fh.write("/* Generated by tools/build-assets.py — do not edit by hand.\n")
    fh.write("   Source: dea-web-viewer/public/data (synced from the canonical dea-metamodel). */\n")
    fh.write("window.DEA_DATA = ")
    json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))
    fh.write(";\n")

print("icons: %d → js/icons.js" % len(icons))
print("entities: %d, relationships: %d (%d typed + %d specializes), definitions: %d → js/data.js"
      % (len(entities), len(rels), len(graph["relationships"]),
         len(rels) - len(graph["relationships"]), len(defs)))
